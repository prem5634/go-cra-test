#!/usr/bin/env python3
"""
Violation Data Printer
Iterates through violation dictionaries and prints specific fields
"""

from typing import List, Dict, Any


def print_violation_details(violations: List[Dict[str, Any]]) -> None:
    """
    Print specific fields from a list of violation dictionaries.
    
    Args:
        violations: List of violation dictionaries containing comment data
    """
    if not violations:
        print("No violations found.")
        return
    
    print("=" * 80)
    print("VIOLATION DETAILS")
    print("=" * 80)
    
    for idx, violation in enumerate(violations, start=1):
        print(f"\n{'─' * 80}")
        print(f"Violation #{idx}")
        print(f"{'─' * 80}")
        
        # Get the first comment from the comment list
        if violation.get("comment") and len(violation["comment"]) > 0:
            comment = violation["comment"][0]
            
            # Print requested fields
            print(f"ID (chunk_id):              {comment.get('chunk_id', 'N/A')}")
            print(f"SRS:                        {comment.get('srs', 'N/A')}")
            print(f"Importance:                 {comment.get('importance', 'N/A')}")
            print(f"Severity:                   {comment.get('severity', 'N/A')}")
            print(f"Rule ID:                    {comment.get('rule_id', 'N/A')}")
            print(f"Rule Label:                 {comment.get('rule_label', 'N/A')}")
            print(f"Generated by Custom Guide line:     {comment.get('generated_by_custom_guideline', 'N/A')}")
            print(f"Custom Guideline ID:        {comment.get('custom_guideline_id', 'N/A')}")

            rule_citations = comment.get('rule_citations', [])
            if len(rule_citations) > 0 :
                print(
                    f"Rule Citations:             rule_file_relative_path: {comment.get('rule_citations')[0].get("rule_file_relative_path")}, source: {comment.get('rule_citations')[0].get("source")}")
            else:
                print(f"Rule Citations:        {comment.get('rule_citations', [])}")

            # Additional context
            print(f"\nFile:                       {violation.get('filename', 'N/A')}")
            print(f"Line Range:                 {violation.get('range', 'N/A')}")
            print(f"Issue:                      {comment.get('issue', 'N/A')}")
        else:
            print("No comment data available for this violation.")
    
    print(f"\n{'=' * 80}")
    print(f"Total Violations: {len(violations)}")
    print(f"{'=' * 80}\n")


def print_violation_summary(violations: List[Dict[str, Any]]) -> None:
    """
    Print a compact summary table of violations.
    
    Args:
        violations: List of violation dictionaries containing comment data
    """
    if not violations:
        print("No violations found.")
        return
    
    print("\n" + "=" * 120)
    print(f"{'#':<4} {'ID':<38} {'SRS':<5} {'Importance':<12} {'Severity':<10} {'Rule':<6} {'Custom GL':<10} {'Citations':<10}")
    print("=" * 120)
    
    for idx, violation in enumerate(violations, start=1):
        if violation.get("comment") and len(violation["comment"]) > 0:
            comment = violation["comment"][0]
            
            chunk_id = comment.get('chunk_id', 'N/A')[:36] + '..' if len(str(comment.get('chunk_id', ''))) > 36 else comment.get('chunk_id', 'N/A')
            srs = comment.get('srs', 'N/A')
            importance = comment.get('importance', 'N/A')
            severity = comment.get('severity', 'N/A')
            rule_id = comment.get('rule_id', 'N/A')
            custom_gl = 'Yes' if comment.get('generated_by_custom_guideline') else 'No'
            citations_count = len(comment.get('rule_citations', []))
            
            print(f"{idx:<4} {chunk_id:<38} {srs:<5} {importance:<12} {severity:<10} {rule_id:<6} {custom_gl:<10} {citations_count:<10}")
    
    print("=" * 120 + "\n")


